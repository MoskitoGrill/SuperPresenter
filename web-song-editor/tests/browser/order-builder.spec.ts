import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('two-column order, drag, keyboard, selected lines and safe XML roundtrip', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('./');
  await page.getByLabel('Název písně', { exact: true }).fill('Nové pořadí');
  await page.getByLabel('Sloka 1', { exact: true }).fill('První řádek\n\nDruhý řádek\nТретій рядок\nČtvrtý řádek');
  await page.getByRole('button', { name: 'Refrén', exact: true }).click();
  await page.getByLabel('Refrén 1', { exact: true }).fill('Sdílený refrén');
  const available = page.locator('.available-parts');
  for (const name of ['Sloka 1', 'Refrén 1', 'Sloka 1']) await available.getByRole('button', { name, exact: true }).click();
  const rows = page.locator('.order-list > li[data-index]');
  await expect(rows).toHaveCount(3);
  await rows.nth(0).dragTo(rows.nth(2), { targetPosition: { x: 40, y: 48 } });
  // Drop in the lower half of the last item moves the first item to the end.
  await expect(page.locator('#preview pre')).toHaveText(['Sdílený refrén', 'První řádek\n\nDruhý řádek\nТретій рядок\nČtvrtý řádek', 'První řádek\n\nDruhý řádek\nТретій рядок\nČtvrtý řádek']);
  await page.locator('.order-handle').nth(0).focus(); await page.keyboard.press('Alt+ArrowDown');
  await expect(page.locator('.order-handle').nth(1)).toBeFocused();
  await available.getByRole('button', { name: 'Řádky', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Přidat vybrané řádky' });
  await dialog.getByLabel('Část písně', { exact: true }).selectOption('v1');
  await dialog.getByLabel('Druhý řádek', { exact: true }).check();
  await dialog.getByLabel('Третій рядок', { exact: true }).check();
  await page.screenshot({ path: 'test-output/order-lines-dialog.png' });
  await dialog.getByRole('button', { name: 'Zrušit', exact: true }).click();
  await expect(rows).toHaveCount(3);
  await available.getByRole('button', { name: 'Řádky', exact: true }).click();
  await dialog.getByLabel('Druhý řádek', { exact: true }).check();
  await dialog.getByLabel('Третій рядок', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Přidat do pořadí', exact: true }).click();
  await expect(rows).toHaveCount(4);
  await expect(page.locator('#preview pre').last()).toHaveText('Druhý řádek\nТретій рядок');
  await rows.last().getByRole('button', { name: 'Řádky', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Změnit výběr řádků' });
  await edit.getByLabel('Третій рядок', { exact: true }).uncheck();
  await edit.getByLabel('Čtvrtý řádek', { exact: true }).check();
  await edit.getByRole('button', { name: 'Použít vybrané řádky', exact: true }).click();
  await expect(rows).toHaveCount(5);
  await expect(page.locator('#preview pre').nth(3)).toHaveText('Druhý řádek');
  await expect(page.locator('#preview pre').nth(4)).toHaveText('Čtvrtý řádek');
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'test-output/order-builder.png', fullPage: true });
  const id = await page.locator('#app').getAttribute('data-song-id');
  await page.getByText('Stáhnout', { exact: true }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'XML', exact: true }).click()]);
  await download.saveAs('test-output/browser-order-builder.xml');
  const xml = readFileSync('test-output/browser-order-builder.xml', 'utf8');
  expect(xml).toContain('v1 r1 v1 v1.2 v1.4');
  await page.getByLabel('Otevřít XML', { exact: true }).setInputFiles('test-output/browser-order-builder.xml');
  await expect(page.locator('#app')).toHaveAttribute('data-song-id', id!);
  await expect(rows).toHaveCount(5);
  for (let i = 0; i < 5; i++) await rows.first().getByRole('button', { name: /Odebrat výskyt/ }).click();
  await expect(page.locator('#preview')).toContainText('Přidejte části');
  await available.getByRole('button', { name: 'Refrén 1', exact: true }).click();
  await expect(page.locator('#preview pre')).toHaveText(['Sdílený refrén']);
});

test('select and clear several lines by dragging while clicks and keyboard still work', async ({ page }) => {
  await page.goto('./');
  await page.getByLabel('Sloka 1', { exact: true }).fill('Jeden\nDva\nTři\nČtyři');
  await page.locator('.add-lines').click();
  const dialog = page.getByRole('dialog', { name: 'Přidat vybrané řádky' });
  const labels = dialog.locator('[data-line-row]');
  const checks = dialog.getByRole('checkbox');
  async function sweep(from: number, to: number) {
    const start = (await labels.nth(from).boundingBox())!, end = (await labels.nth(to).boundingBox())!;
    await page.mouse.move(start.x + 90, start.y + start.height / 2);
    await page.mouse.down();
    await page.mouse.move(end.x + 90, end.y + end.height / 2, { steps: 12 });
    await page.mouse.up();
  }
  await sweep(0, 3);
  for (let i = 0; i < 4; i++) await expect(checks.nth(i)).toBeChecked();
  await sweep(3, 1);
  await expect(checks.nth(0)).toBeChecked();
  for (let i = 1; i < 4; i++) await expect(checks.nth(i)).not.toBeChecked();
  await checks.nth(1).focus(); await page.keyboard.press('Space');
  await expect(checks.nth(1)).toBeChecked();
  await labels.nth(3).locator('span').click();
  await expect(checks.nth(3)).toBeChecked();
  await checks.nth(1).uncheck();
  await dialog.getByRole('button', { name: 'Přidat do pořadí', exact: true }).click();
  await expect(page.locator('#preview pre')).toHaveText(['Jeden', 'Čtyři']);
  await page.locator('.add-lines').click();
  await sweep(1, 2); await page.keyboard.press('Escape');
  await expect(page.locator('#preview pre')).toHaveText(['Jeden', 'Čtyři']);
  await expect(page.locator('.add-lines')).toBeFocused();
});

test('reuse a whole line selection repeatedly and restore its shortcuts with the draft', async ({ page }) => {
  await page.goto('./');
  await page.getByLabel('Název písně', { exact: true }).fill('Opakované řádky');
  await page.getByLabel('Sloka 1', { exact: true }).fill('Jeden\nDva\nTři');
  await page.locator('.add-lines').click();
  const dialog = page.getByRole('dialog', { name: 'Přidat vybrané řádky' });
  await dialog.getByLabel('Jeden', { exact: true }).check();
  await dialog.getByLabel('Tři', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Přidat do pořadí', exact: true }).click();
  const shortcuts = page.locator('.saved-line-selections > button');
  await expect(shortcuts).toHaveText(['Sloka 1 · řádky 1, 3']);
  await shortcuts.first().click();
  await expect(shortcuts.first()).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(shortcuts).toHaveCount(1);
  await expect(page.locator('#preview pre')).toHaveText(['Jeden', 'Tři', 'Jeden', 'Tři', 'Jeden', 'Tři']);
  page.once('dialog', d => d.accept()); await page.reload();
  await expect(shortcuts).toHaveText(['Sloka 1 · řádky 1, 3']);
  const rows = page.locator('.order-list > li[data-index]');
  for (let i = 0; i < 6; i++) await rows.first().getByRole('button', { name: /Odebrat výskyt/ }).click();
  await expect(shortcuts).toHaveCount(1);
  await shortcuts.first().click();
  await expect(page.locator('#preview pre')).toHaveText(['Jeden', 'Tři']);
  await page.getByLabel('Sloka 1', { exact: true }).fill('Upravený první\nDva\nUpravený třetí');
  await expect(page.locator('#preview pre')).toHaveText(['Upravený první', 'Upravený třetí']);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'test-output/reusable-lines.png', fullPage: true });
});
