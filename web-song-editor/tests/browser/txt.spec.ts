import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

const human = 'Ukázková píseň\r\n\r\nsloka1\r\nŽluťoučký kůň.\r\n\r\nREFREN 1\r\nČeský refrén.\r\n\r\nSloka 2\r\nDruhá sloka.\r\n\r\nRefrén\r\n';
test('plain TXT, empty template, title collision and safe language-only update', async ({ page }) => {
  await page.goto('/');
  const upload = async (text: string) => page.getByLabel('Importovat TXT', { exact: true }).setInputFiles({ name: 'pisnicka.txt', mimeType: 'text/plain', buffer: Buffer.from(text) });
  const [template] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Stáhnout prázdnou TXT šablonu', exact: true }).click()]);
  const blank = readFileSync((await template.path())!, 'utf8');
  expect(blank).toContain('Sloka 1\r\n\r\nRefrén 1\r\n\r\nBridge 1');
  expect(blank).not.toContain('#'); expect(blank).not.toContain(':');
  await upload(human);
  const preview = page.getByRole('region', { name: 'Náhled importu TXT', exact: true });
  await expect(preview).toContainText('v1 → r1 → v2 → r1');
  await expect(page.getByLabel('Cíl importu TXT')).toHaveCount(0);
  page.once('dialog', d => d.dismiss());
  await page.getByRole('button', { name: 'Importovat jako novou píseň', exact: true }).click();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Nová píseň');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Importovat jako novou píseň', exact: true }).click();
  const id = (await page.locator('#state').innerText()).split('ID: ')[1];
  page.once('dialog', d => d.accept('ukrajinština'));
  await page.getByRole('button', { name: 'Přidat jazyk', exact: true }).click();
  await page.getByLabel('v1', { exact: true }).fill('Український текст');
  await page.getByLabel('r1', { exact: true }).fill('Приспів');
  await page.getByLabel('v2', { exact: true }).fill('Другий куплет');
  // Export offers a language even with multiple variants; no technical lines.
  await page.getByRole('button', { name: 'Stáhnout TXT', exact: true }).click();
  await page.getByLabel('Jazyk pro TXT', { exact: true }).selectOption('0');
  const [txt] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Stáhnout vybraný jazyk do TXT', exact: true }).click()]);
  const exported = readFileSync((await txt.path())!, 'utf8');
  expect(exported).not.toContain(id); expect(exported).not.toContain('#'); expect(exported).not.toContain(':');
  expect(exported).toContain('Sloka 1\r\n'); expect(exported).not.toContain('Український');
  await upload(exported.replace('Český refrén.', 'Upravený český refrén.'));
  await expect(preview).toContainText('stejným názvem');
  await page.getByLabel('Jazyk pro přepsání textů', { exact: true }).selectOption('0');
  page.once('dialog', d => d.dismiss());
  await page.getByRole('button', { name: 'Přepsat texty vybraného jazyka', exact: true }).click();
  await expect(page.getByLabel('Jazyková varianta', { exact: true })).toHaveValue('1');
  const accept = (d: import('@playwright/test').Dialog) => d.accept(); page.on('dialog', accept);
  await page.getByRole('button', { name: 'Přepsat texty vybraného jazyka', exact: true }).click();
  page.off('dialog', accept);
  await expect(page.locator('#state')).toContainText(id);
  await expect(page.locator('#preview pre')).toHaveText(['Žluťoučký kůň.', 'Upravený český refrén.', 'Druhá sloka.', 'Upravený český refrén.']);
  await page.getByLabel('Jazyková varianta', { exact: true }).selectOption('1');
  await expect(page.getByLabel('v1', { exact: true })).toHaveValue('Український текст');
  await page.getByLabel('Jazyková varianta', { exact: true }).selectOption('0');
  const [xml] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Stáhnout XML', exact: true }).click()]);
  await xml.saveAs('test-output/browser-txt.xml');
  await upload(human);
  page.once('dialog', d => d.dismiss());
  await page.getByRole('button', { name: 'Vytvořit novou s jiným názvem', exact: true }).click();
  await expect(page.locator('#state')).toContainText(id);
  page.once('dialog', d => d.accept('Ukázková píseň — nová'));
  await page.getByRole('button', { name: 'Vytvořit novou s jiným názvem', exact: true }).click();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Ukázková píseň — nová');
  await expect(page.locator('#state')).not.toContainText(id);
  await upload('Chyba\nRefrén\n');
  await expect(preview).toContainText('neexistující');
  await expect(page.getByRole('button', { name: 'Importovat jako novou píseň', exact: true })).toBeDisabled();
  await upload(human + '\nRefrén\nJiný text\n\nRefrén\nJiný text\n\nRefrén\n');
  await expect(page.getByRole('button', { name: 'Importovat jako novou píseň', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Vyřešit odlišné texty vytvořením variant', exact: true }).click();
  await expect(preview).toContainText('v1 → r1 → v2 → r1 → r2 → r2 → r2');
  await expect(preview.locator('pre')).toHaveText(['Žluťoučký kůň.', 'Český refrén.', 'Druhá sloka.', 'Jiný text']);
});
