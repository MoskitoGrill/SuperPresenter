import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
test('create song, shared chorus, identity and safe replacement', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Název písně', { exact: true }).fill('Ruční zkouška');
  await page.getByLabel('v1', { exact: true }).fill('První sloka');
  await page.getByRole('button', { name: 'Přidat: Sloka', exact: true }).click();
  await page.getByLabel('v2', { exact: true }).fill('Druhá sloka');
  await page.getByRole('button', { name: 'Přidat: Refrén', exact: true }).click();
  await page.getByLabel('r1', { exact: true }).fill('Refrén');
  for (const id of ['r1','v2','r1']) await page.getByRole('button', { name: `Zařadit ${id}`, exact: true }).click();
  await page.getByLabel('r1', { exact: true }).fill('Změněný refrén');
  await expect(page.locator('#preview pre')).toHaveText(['První sloka','Změněný refrén','Druhá sloka','Změněný refrén']);
  const state = await page.locator('#state').innerText();
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Nová píseň', exact: true }).click();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Ruční zkouška');
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Stáhnout XML', exact: true }).click()]);
  expect(download.suggestedFilename()).toBe('Ruční zkouška.xml');
  await download.saveAs('test-output/browser-song.xml');
  const exported = readFileSync('test-output/browser-song.xml', 'utf-8');
  expect(exported).toContain('v1 r1 v2 r1');
  expect(exported.match(/<section name="r1">/g)).toHaveLength(1);
  await expect(page.locator('#state')).toContainText(state.split('ID: ')[1]);
  page.once('dialog', dialog => dialog.accept('Moje kopie'));
  await page.getByRole('button', { name: 'Vytvořit kopii', exact: true }).click();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Moje kopie');
  expect(await page.locator('#state').innerText()).not.toContain(state.split('ID: ')[1]);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Vrátit původní koncept', exact: true }).click();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Ruční zkouška');
  await page.getByLabel('Otevřít XML', { exact: true }).setInputFiles('test-output/browser-song.xml');
  await expect(page.locator('#state')).toContainText(state.split('ID: ')[1]);
  await expect(page.locator('#preview pre')).toHaveText(['První sloka','Změněný refrén','Druhá sloka','Změněný refrén']);
  const rejected = page.waitForEvent('dialog');
  await page.getByLabel('Otevřít XML', { exact: true }).setInputFiles({ name: 'bad.xml', mimeType: 'application/xml', buffer: Buffer.from('<slide><broken>') });
  const diagnostic = await rejected;
  expect(diagnostic.message()).toContain('Neplatné XML'); await diagnostic.accept();
  await expect(page.getByLabel('Název písně', { exact: true })).toHaveValue('Ruční zkouška');
});
