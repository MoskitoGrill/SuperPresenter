import { test, expect } from '@playwright/test';

for (const viewport of [{ width: 1280, height: 720 }, { width: 390, height: 844 }]) {
  test(`comfortable workflow ${viewport.width}`, async ({ page }) => {
    await page.setViewportSize(viewport);
    await page.goto('./');
    await expect(page.locator('.workspace > div')).toHaveCount(2);
    await expect(page.locator('#sequence > :last-child')).toHaveAttribute('id', 'result');
    await expect(page.locator('#preview')).not.toBeVisible();
    await expect(page.getByRole('heading', { name: 'Baptisté Šumperk', exact: true })).toBeVisible();
    await expect(page.locator('.main-actions > button')).toHaveText(['Nová píseň', 'Otevřít', 'Importovat']);
    const title = page.getByLabel('Název písně', { exact: true });
    await expect(title).toHaveValue('');
    await expect(title).toHaveAttribute('placeholder', 'Zadejte název písně');
    const before = await title.boundingBox();
    await page.getByText('Stáhnout šablonu', { exact: true }).click();
    const popup = page.locator('.template-options').first();
    await expect(popup).toBeVisible();
    expect(await title.boundingBox()).toEqual(before);
    const optionsBox = (await popup.boundingBox())!;
    const menuBox = (await page.locator('.template-menu').first().boundingBox())!;
    expect(optionsBox.y).toBeGreaterThanOrEqual(menuBox.y + menuBox.height);
    await page.screenshot({ path: `test-output/templates-${viewport.width}.png` });
    await page.keyboard.press('Escape');
    await expect(popup).not.toBeVisible();
    await expect(page.locator('#state')).toHaveCount(0);
    await expect(page.locator('#feedback')).toBeEmpty();
    const chooserEvent = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Importovat', exact: true }).click();
    const chooser = await chooserEvent;
    expect(await chooser.element().getAttribute('accept')).toMatch(/\.txt,\.docx/);
    await chooser.setFiles([]);
    await expect(page.getByText('Stáhnout', { exact: true })).toBeVisible();
    await expect(page.locator('.export-menu').getByRole('button', { name: 'TXT', exact: true })).not.toBeVisible();
    await page.getByLabel('Název písně', { exact: true }).fill('Zkouška pohodlí');
    await page.getByLabel('Sloka 1', { exact: true }).fill('První sloka\nDalší řádek');
    await page.getByRole('button', { name: 'Refrén', exact: true }).click();
    await expect(page.getByLabel('Refrén 1', { exact: true })).toBeFocused();
    await page.keyboard.type('Společný refrén');
    await page.locator('.available-parts').getByRole('button', { name: 'Sloka 1', exact: true }).click();
    await page.locator('.available-parts').getByRole('button', { name: 'Refrén 1', exact: true }).click();
    await page.keyboard.press('Enter');
    await expect(page.locator('#preview pre')).toHaveText(['První sloka\nDalší řádek', 'Společný refrén', 'Společný refrén']);
    await page.locator('.order-handle').nth(2).focus();
    await page.keyboard.press('Alt+ArrowUp');
    await expect(page.locator('.order-handle').nth(1)).toBeFocused();
    await page.locator('.order-handle').nth(1).click();
    await expect(page.getByLabel('Refrén 1', { exact: true })).toBeFocused();
    await page.getByLabel('Refrén 1', { exact: true }).fill('Upravený společný refrén');
    await expect(page.locator('#preview pre')).toHaveText(['První sloka\nDalší řádek', 'Upravený společný refrén', 'Upravený společný refrén']);
    await expect(page.getByRole('navigation', { name: 'Pracovní oblasti' })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const previewToggle = page.locator('#result > summary');
    await previewToggle.focus(); await page.keyboard.press('Enter');
    await expect(page.locator('#preview')).toBeVisible();
    await page.screenshot({ path: `test-output/preview-expanded-${viewport.width}.png`, fullPage: true });
    await previewToggle.press('Space');
    await expect(page.locator('#preview')).not.toBeVisible();
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: `test-output/viewport-${viewport.width}.png` });
    await page.screenshot({ path: `test-output/layout-${viewport.width}.png`, fullPage: true });
    const id = (await page.locator('#app').getAttribute('data-song-id'))!;
    page.once('dialog', d => d.accept()); await page.reload();
    await expect(page.locator('footer #recovery-status')).toContainText('obnovena');
    await expect(page.locator('#app')).toHaveAttribute('data-song-id', id);
    await page.getByText('Stáhnout', { exact: true }).click();
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'XML', exact: true }).click()]);
    expect(download.suggestedFilename()).toBe('Zkouška pohodlí.xml');
    await expect(page.locator('#feedback')).toContainText('Původní soubor na disku se nezměnil');
  });
}
